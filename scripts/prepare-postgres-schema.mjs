import { readFile, writeFile, mkdir, cp } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname } from "node:path";

const sourcePath = fileURLToPath(new URL("../prisma/schema.prisma", import.meta.url));
const targetPath = fileURLToPath(
  new URL("../prisma/schema.postgresql.prisma", import.meta.url),
);
const source = await readFile(sourcePath, "utf8");
const datasourcePattern =
  /datasource db\s*\{\s*provider\s*=\s*"sqlite"\s*url\s*=\s*env\("DATABASE_URL"\)\s*\}/;

if (!datasourcePattern.test(source)) {
  throw new Error("Could not find the expected SQLite datasource in prisma/schema.prisma.");
}

const postgresSchema = source.replace(
  datasourcePattern,
  `datasource db {
  provider  = "postgresql"
  url       = env("DATABASE_URL")
  directUrl = env("DIRECT_URL")
}`,
);

await writeFile(targetPath, postgresSchema, "utf8");

// Backup SQLite migrations
const sqliteMigrationsDir = fileURLToPath(new URL("../prisma/migrations-sqlite", import.meta.url));
const currentMigrationsDir = fileURLToPath(new URL("../prisma/migrations", import.meta.url));
const postgresMigrationsDir = fileURLToPath(new URL("../prisma/migrations-postgresql", import.meta.url));

// Create PostgreSQL-specific migration lock directory
await mkdir(postgresMigrationsDir, { recursive: true });

const postgresLockPath = fileURLToPath(
  new URL("../prisma/migrations-postgresql/migration_lock.toml", import.meta.url),
);
const lockContent = `# Please do not edit this file manually
# It should be added in your version-control system (e.g., Git)
provider = "postgresql"
`;
await writeFile(postgresLockPath, lockContent, "utf8");

// Copy PostgreSQL migrations to main migrations directory for deploy
// Note: prisma migrate deploy doesn't support --migrations-dir flag
try {
  await cp(postgresMigrationsDir, currentMigrationsDir, { recursive: true, force: true });
  console.log("Copied PostgreSQL migrations to main migrations directory.");
} catch (error) {
  console.error("Failed to copy migrations:", error);
  throw error;
}

console.log("Prepared PostgreSQL Prisma schema and migration lock.");
